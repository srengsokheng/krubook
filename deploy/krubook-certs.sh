#!/usr/bin/env bash
# Gets Let's Encrypt certificates with certbot (webroot) for each name that already points at this
# server, then rewrites the nginx site to match the certificates that exist. Runs every 15 minutes
# from krubook-certs.timer, so a new domain gets HTTPS on its own once its DNS is live.
# Renewal is certbot's own timer; the deploy hook reloads nginx.
set -euo pipefail
. /etc/krubook/domains   # DOMAIN=..., HOST=...
IP=$(curl -fs4 https://api.ipify.org || hostname -I | awk '{print $1}')
WEBROOT=/var/www/certbot
mkdir -p "$WEBROOT"

points_here() { [ "$(dig +short "$1" A @1.1.1.1 | grep -E '^[0-9.]+$' | tail -1)" = "$IP" ]; }
have() { [ -f "/etc/letsencrypt/live/$1/fullchain.pem" ]; }
obtain() { certbot certonly --webroot -w "$WEBROOT" --cert-name "$1" "${@:2}" --non-interactive --agree-tos --register-unsafely-without-email --keep-until-expiring -q; }

if ! have "$HOST" && points_here "$HOST"; then obtain "$HOST" -d "$HOST" || echo "certbot failed for $HOST"; fi
if ! have "$DOMAIN" && points_here "$DOMAIN"; then
  if points_here "www.$DOMAIN"; then obtain "$DOMAIN" -d "$DOMAIN" -d "www.$DOMAIN" || echo "certbot failed for $DOMAIN"
  else obtain "$DOMAIN" -d "$DOMAIN" || echo "certbot failed for $DOMAIN"; fi
fi

proxy='
    client_max_body_size 200m;
    location / {
        proxy_pass http://127.0.0.1:4310;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
    }'
tls() { echo "    listen 443 ssl http2; listen [::]:443 ssl http2;
    ssl_certificate /etc/letsencrypt/live/$1/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$1/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:krubook:10m;
    ssl_session_timeout 1d;
    add_header Strict-Transport-Security \"max-age=31536000\" always;
    add_header X-Content-Type-Options nosniff always;
    add_header Referrer-Policy same-origin always;"; }

# Where plain-HTTP visitors go: the domain once it has a certificate, else the fallback name.
if have "$DOMAIN"; then canonical="$DOMAIN"; elif have "$HOST"; then canonical="$HOST"; else canonical=""; fi

{
  echo "# Generated by /opt/krubook/app/deploy/krubook-certs.sh. Do not edit by hand."
  echo "server {
    listen 80 default_server; listen [::]:80 default_server;
    server_name _;
    location /.well-known/acme-challenge/ { root $WEBROOT; }"
  if [ -n "$canonical" ]; then echo "    location / { return 301 https://$canonical\$request_uri; }"; else echo "$proxy"; fi
  echo "}"
  if have "$DOMAIN"; then
    echo "server {
    server_name $DOMAIN;
$(tls "$DOMAIN")
$proxy
}"
    if openssl x509 -in "/etc/letsencrypt/live/$DOMAIN/fullchain.pem" -noout -text | grep -q "DNS:www.$DOMAIN"; then
      echo "server {
    server_name www.$DOMAIN;
$(tls "$DOMAIN")
    return 301 https://$DOMAIN\$request_uri;
}"
    fi
  fi
  if have "$HOST"; then
    echo "server {
    server_name $HOST;
$(tls "$HOST")"
    if have "$DOMAIN"; then echo "    return 301 https://$DOMAIN\$request_uri;"; else echo "$proxy"; fi
    echo "}"
  fi
} > /etc/nginx/sites-available/krubook.new

mv /etc/nginx/sites-available/krubook.new /etc/nginx/sites-available/krubook
ln -sf /etc/nginx/sites-available/krubook /etc/nginx/sites-enabled/krubook
rm -f /etc/nginx/sites-enabled/default
nginx -t -q && systemctl reload nginx
